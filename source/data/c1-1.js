    "Trois formes : le <b>participe présent</b> (-ing) pour une action simultanée ou une cause (<em>Feeling tired, she went to bed</em>) ; le <b>participe passé</b> pour un sens passif (<em>Built in 1900, the house needs repairs</em> = la maison, qui a été construite en 1900) ; le <b>participe parfait</b> <em>having + participe passé</em> pour une action terminée avant l'autre (<em>Having finished her report, she left</em>).",
    "Règle d'or : le sujet sous-entendu de la participiale doit être <b>le même</b> que celui de la proposition principale. <em>Walking down the street, the trees looked beautiful</em> est faux (les arbres ne marchent pas !) : c'est le fameux <b>dangling participle</b>. On corrige : <em>Walking down the street, I noticed how beautiful the trees were.</em>",
