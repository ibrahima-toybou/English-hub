// Build the standalone website (GitHub Pages / Vercel).
// Usage: node build-site.js <outDir>      (default: the folder above this one, i.e. the repository root)
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const root = __dirname;
const out = path.resolve(process.argv[2] || path.join(root, ".."));
fs.mkdirSync(out, { recursive: true });

const dataDir = path.join(root, "data");
const order = f => (f.startsWith("tables") || f.startsWith("extras") || f.startsWith("vocab")) ? "z" + f : f;
const dataFiles = fs.readdirSync(dataDir).filter(f => f.endsWith(".js")).sort((a, b) => order(a).localeCompare(order(b)));
let data = "";
for (const f of dataFiles) {
  const src = fs.readFileSync(path.join(dataDir, f), "utf8");
  if (/<\/script/i.test(src)) throw new Error(f + " contains </script");
  data += "/* " + f + " */\n" + src + "\n";
}
const app = fs.readFileSync(path.join(root, "src/app.js"), "utf8");
const head = fs.readFileSync(path.join(root, "src/head.html"), "utf8").replace(/<meta name="claude:viewport-fit-sides"[^>]*>\n?/, "");
const body = fs.readFileSync(path.join(root, "src/body.html"), "utf8");
const desc = "Programme d'anglais de A2 à C2 : 68 leçons de grammaire, 25 listes de vocabulaire, révisions espacées, dictées et prononciation.";

const html = `<!doctype html>
<html lang="fr">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="description" content="${desc}">
<meta name="theme-color" content="#ffffff" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#151a2d" media="(prefers-color-scheme: dark)">
<meta property="og:title" content="English Learning Hub">
<meta property="og:description" content="${desc}">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="English Hub">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" href="icon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<style>:root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style>
${head}
</head>
<body>
${body}
<script>window.EHUB_STANDALONE = true;</script>
<script>
${data}</script>
<script>
${app}</script>
</body>
</html>
`;
fs.writeFileSync(path.join(out, "index.html"), html);

const manifest = {
  name: "English Learning Hub",
  short_name: "English Hub",
  description: desc,
  lang: "fr",
  start_url: "./",
  scope: "./",
  display: "standalone",
  background_color: "#f3f4f8",
  theme_color: "#151a2d",
  icons: [
    { src: "icon-192.png", sizes: "192x192", type: "image/png" },
    { src: "icon-512.png", sizes: "512x512", type: "image/png" },
    { src: "icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" }
  ]
};
fs.writeFileSync(path.join(out, "manifest.webmanifest"), JSON.stringify(manifest, null, 2) + "\n");

// Offline support: network first (so updates show up at once), cached copy when offline.
const version = crypto.createHash("sha1").update(html).digest("hex").slice(0, 10);
const assets = ["./", "index.html", "manifest.webmanifest", "icon.svg", "icon-192.png", "icon-512.png", "apple-touch-icon.png"];
const sw = `// English Learning Hub — offline support. Generated by build-site.js
const CACHE = "ehub-${version}";
const ASSETS = ${JSON.stringify(assets)};
self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  const cacheable = url.origin === location.origin || /(^|\\.)fonts\\.(googleapis|gstatic)\\.com$/.test(url.hostname);
  if (!cacheable) return;
  e.respondWith(
    fetch(req).then(res => {
      if (res.ok || res.type === "opaque") { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
      return res;
    }).catch(() => caches.match(req).then(hit => hit || (req.mode === "navigate" ? caches.match("index.html") : Response.error())))
  );
});
`;
fs.writeFileSync(path.join(out, "sw.js"), sw);
fs.writeFileSync(path.join(out, ".nojekyll"), "");
console.log("site built in", out, "·", (html.length / 1024).toFixed(0) + " KB · cache", version);
